#!/usr/bin/env python3
"""Generate original, redistributable raster/UV passes; no third-party assets."""
from pathlib import Path
import json
import numpy as np
from PIL import Image, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "public/product-assets/mockup-scenes/original-cup"
OUT.mkdir(parents=True, exist_ok=True)
W,H=1024,1365
Y,X=np.mgrid[0:H,0:W]
# Soft studio backdrop with original contact and cast shadows.
radius=np.sqrt(((X-W*.46)/W)**2+((Y-H*.30)/H)**2)
bg=np.clip(242-radius*19,222,244).astype(np.uint8)
base=Image.fromarray(np.stack([bg,np.minimum(bg+1,255),np.minimum(bg+3,255),np.full_like(bg,255)],axis=-1))
shadow=Image.new('RGBA',(W,H));d=ImageDraw.Draw(shadow)
d.ellipse((268,1114,847,1220),fill=(42,45,48,53));shadow=shadow.filter(ImageFilter.GaussianBlur(31));base.alpha_composite(shadow)
contact=Image.new('RGBA',(W,H));ImageDraw.Draw(contact).ellipse((323,1147,712,1202),fill=(35,39,42,52));contact=contact.filter(ImageFilter.GaussianBlur(10));base.alpha_composite(contact)
bodymask=Image.new('L',(W,H));bd=ImageDraw.Draw(bodymask)
bd.polygon([(253,419),(771,419),(692,1160),(332,1160)],fill=255)
bd.ellipse((332,1131,692,1188),fill=255)
# Smooth but asymmetric paper lighting, with a distinctly shaded right edge.
r=(259-(Y-419)*(79/741))
x=(X-512)/np.maximum(r,1)
light=np.clip(246 - 34*np.clip(x,0,1)**1.6 - 13*np.clip(-x,0,1)**2 + 5*np.exp(-((x+.40)/.36)**2) - 8*np.clip((Y-1000)/220,0,1),192,252)
rgb=np.stack([light,light*.999,light*.993],axis=-1).astype(np.uint8)
body=Image.fromarray(np.dstack([rgb,np.array(bodymask)]));base.alpha_composite(body)
# Rolled rim and inset opening. These are original vectors rendered to pixels.
d=ImageDraw.Draw(base)
d.ellipse((250,371,774,463),fill=(245,245,243),outline=(218,220,220),width=3)
d.ellipse((267,382,757,449),fill=(202,204,205),outline=(228,230,222),width=4)
d.ellipse((278,389,746,444),fill=(222,223,224))
d.arc((254,374,770,461),0,180,fill=(254,254,252),width=11)
d.arc((260,379,764,455),180,360,fill=(255,255,254),width=6)
# Printable full front panel follows the tapered surface with a cylindrical warp.
ytop,ybottom=466,1120
v=np.clip((Y-ytop)/(ybottom-ytop),0,1)
rprint=248-(Y-ytop)*(70/(ybottom-ytop))
xn=(X-512)/np.maximum(rprint,1)
coverage=((Y>=ytop)&(Y<=ybottom)&(np.abs(xn)<=1)).astype(np.uint8)*255
# Keep 16-bit UV values for typography; an 8-bit map causes visible stepping.
u=(np.arcsin(np.clip(xn,-1,1))/np.pi+.5)
lookup=np.empty((H,W,2),dtype='<u2');lookup[:,:,0]=np.round(u*65535).astype('<u2');lookup[:,:,1]=np.round(v*65535).astype('<u2')
lookup.tofile(OUT/'front.uv.bin')
mask=np.stack([coverage,coverage,coverage,np.full_like(coverage,255)],axis=-1)
Image.fromarray(mask).save(OUT/'front-mask.png',optimize=True)
# Highlights stay separate and blend above the customer's artwork.
glint=np.clip(12*np.exp(-((xn+.62)/.12)**2)*(coverage/255),0,255).astype(np.uint8)
Image.fromarray(np.stack([np.full_like(glint,255)]*3+[glint],axis=-1)).save(OUT/'highlights.png',optimize=True)
base.save(OUT/'base.png',optimize=True)
preview=base.copy();preview.thumbnail((300,400));preview.convert('RGB').save(OUT/'thumbnail.jpg',quality=88)
scene={
 'id':'original-cup-studio','title':'Örnek bardak · Stüdyo', 'width':W,'height':H,
 'baseImageUrl':'/product-assets/mockup-scenes/original-cup/base.png',
 'thumbnailUrl':'/product-assets/mockup-scenes/original-cup/thumbnail.jpg',
 'distribution':'public-web','license':'Alaçam projesi için özgün olarak üretilen prosedürel örnek; CC0-1.0.',
 'surfaces':[{'id':'front','face':'front','mapping':{'type':'uv-rg16le','url':'/product-assets/mockup-scenes/original-cup/front.uv.bin'},'maskUrl':'/product-assets/mockup-scenes/original-cup/front-mask.png','blend':'multiply'}],
 'layers':[{'imageUrl':'/product-assets/mockup-scenes/original-cup/highlights.png','blend':'screen','opacity':1}]
}
(OUT/'scene.json').write_text(json.dumps(scene,ensure_ascii=False,indent=2)+'\n')
(OUT/'LICENSE.txt').write_text('Original procedural demo assets generated by scripts/generate-public-mockup-demo.py.\nDedicated to the public domain under CC0 1.0 (https://creativecommons.org/publicdomain/zero/1.0/).\nThese are approximate demo visuals, not photographs or manufacturer production templates.\nNo PSD, third-party photo, texture or model was used.\n')
print(OUT)
